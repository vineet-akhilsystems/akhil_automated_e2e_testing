#!/usr/bin/env node
// Generate tests/modules/<id>/fields.ts from qa/modules/<id>/discovery/fields-*.json
// (written by tests/discovery/module-discovery.spec.ts), in the same shape as tests/modules/registration/fields.ts.
//
//   node qa/tools/scaffold-module-fields.mjs <moduleId> [--dry-run] [--force] [--root <dir>]
//
// Refuses to overwrite an existing fields.ts unless --force. --dry-run prints the file and writes nothing.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const MODULE_ID_RE = /^[a-z][a-z0-9-]*$/;
const KINDS = new Set(['text', 'select', 'date', 'datetime', 'textarea', 'checkbox']);

export function normalizeKind(kind) {
  const k = String(kind || '').toLowerCase();
  if (KINDS.has(k)) return k;
  if (k === 'radio') return 'checkbox';
  if (k === 'datetime-local') return 'datetime';
  return 'text'; // number, email, tel, password, search, unknown...
}

const snake = (s) => s.toLowerCase().replace(/['’]/g, '').replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '');

function q(s) {
  const body = JSON.stringify(String(s)).slice(1, -1);
  return String(s).includes("'") ? `"${body}"` : `'${body.replace(/\\"/g, '"')}'`;
}

/** Order: default first, then the other variants alphabetically. */
function listDiscoveryFiles(dir) {
  const files = fs.readdirSync(dir).filter((f) => /^fields-.+\.json$/.test(f)).sort();
  const first = files.filter((f) => f === 'fields-default.json');
  return [...first, ...files.filter((f) => f !== 'fields-default.json')];
}

export function buildFieldsTs(moduleId, discovered) {
  // discovered: [{ source, fields: [...] }]
  const entries = new Map(); // "card|label" -> { key, def, variants:Set }
  const usedKeys = new Set();
  const order = [];
  for (const { source, fields } of discovered) {
    for (const f of fields) {
      if (!f || !f.label) continue;
      const id = `${f.card ?? ''}|${f.label}`;
      let e = entries.get(id);
      if (!e) {
        let key = snake(f.label) || 'field';
        if (usedKeys.has(key)) key = snake(`${f.card} ${f.label}`) || key;
        for (let i = 2; usedKeys.has(key); i++) key = `${snake(f.label) || 'field'}_${i}`;
        usedKeys.add(key);
        e = { key, def: { card: f.card ?? '', label: f.label, kind: normalizeKind(f.kind), column: f.column || '' }, sources: new Set() };
        entries.set(id, e);
        order.push(e);
      } else if (!e.def.column && f.column) e.def.column = f.column;
      e.sources.add(source);
    }
  }

  const lines = [
    `// Field keys for the ${moduleId} module mapped to where they live on the page.`,
    '// GENERATED by qa/tools/scaffold-module-fields.mjs from qa/modules/' + moduleId + '/discovery/fields-*.json.',
    '// Review before use: keys are derived from labels, so rename them to match the case-file columns.',
    '// column is the backend columnName (name attribute of the input, or of react-select\'s hidden input).',
    "export type FieldKind = 'text' | 'select' | 'date' | 'datetime' | 'textarea' | 'checkbox';",
    '',
    'export interface FieldDef {',
    '  card: string;',
    '  label: string;',
    '  kind: FieldKind;',
    '  column?: string;',
    '}',
    '',
    'export const FIELDS: Record<string, FieldDef> = {',
  ];
  let card = null;
  for (const e of order) {
    if (e.def.card !== card) {
      card = e.def.card;
      lines.push(`  // ${card || '(no card)'}`);
    }
    const only = [...e.sources];
    const note = only.length && !only.includes('default') ? `  // only in: ${only.join(', ')}` : '';
    const col = e.def.column ? `, column: ${q(e.def.column)}` : '';
    lines.push(`  ${/^[a-z_][a-z0-9_]*$/.test(e.key) ? e.key : q(e.key)}: { card: ${q(e.def.card)}, label: ${q(e.def.label)}, kind: ${q(e.def.kind)}${col} },${note}`);
  }
  lines.push(
    '};',
    '',
    '// Fill order follows the page top to bottom. Reorder cascading dropdowns by hand (e.g. country -> pin -> state -> district -> city).',
    'export const FILL_ORDER = [',
  );
  for (let i = 0; i < order.length; i += 6) lines.push('  ' + order.slice(i, i + 6).map((e) => q(e.key)).join(', ') + ',');
  lines.push('];', '');
  return { content: lines.join('\n'), count: order.length };
}

/** Programmatic entry point (used by the CLI and the unit tests). */
export function scaffold({ moduleId, root = process.cwd(), force = false, dryRun = false } = {}) {
  if (!MODULE_ID_RE.test(moduleId || '')) throw new Error(`moduleId must match ${MODULE_ID_RE} (got "${moduleId}")`);
  const dir = path.join(root, 'qa', 'modules', moduleId, 'discovery');
  if (!fs.existsSync(dir)) throw new Error(`No discovery directory: ${dir}. Run MODULE_ID=${moduleId} MODULE_URL=/... npm run module:discover first.`);
  const files = listDiscoveryFiles(dir);
  if (!files.length) throw new Error(`No fields-*.json in ${dir}`);
  const discovered = files.map((f) => {
    const data = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
    if (!Array.isArray(data)) throw new Error(`${f} must be a JSON array of fields`);
    return { source: f.replace(/^fields-|\.json$/g, ''), fields: data };
  });
  const { content, count } = buildFieldsTs(moduleId, discovered);
  const target = path.join(root, 'tests', 'modules', moduleId, 'fields.ts');
  const exists = fs.existsSync(target);
  if (exists && !force && !dryRun) throw new Error(`${target} already exists; pass --force to overwrite (or --dry-run to preview).`);
  if (!dryRun) {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content);
  }
  return { target, content, count, written: !dryRun, existed: exists, sources: files };
}

function main(argv) {
  const args = argv.slice(2);
  const flag = (n) => args.includes(n);
  const ri = args.indexOf('--root');
  const root = ri >= 0 ? path.resolve(args[ri + 1]) : path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
  const moduleId = args.find((a, i) => !a.startsWith('--') && args[i - 1] !== '--root');
  if (!moduleId) {
    console.error('usage: node qa/tools/scaffold-module-fields.mjs <moduleId> [--dry-run] [--force] [--root <dir>]');
    return 2;
  }
  try {
    const r = scaffold({ moduleId, root, force: flag('--force'), dryRun: flag('--dry-run') });
    if (r.written) console.log(`Wrote ${r.target} (${r.count} fields from ${r.sources.join(', ')})${r.existed ? ' [overwritten]' : ''}`);
    else { console.log(r.content); console.error(`--dry-run: ${r.count} fields, would ${r.existed ? 'overwrite' : 'create'} ${r.target}`); }
    return 0;
  } catch (e) {
    console.error(`scaffold-module-fields: ${e.message}`);
    return 1;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) process.exitCode = main(process.argv);
