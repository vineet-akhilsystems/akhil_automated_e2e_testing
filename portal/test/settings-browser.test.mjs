import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { EventEmitter } from 'node:events';
import { chromium, expect } from '@playwright/test';
import { createPortal } from '../server.mjs';

test('BA can save a profile, refresh login and queue selected automation entirely through Settings UI', { timeout: 60000 }, async t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'augastam-settings-browser-'));
  const previousUser = process.env.AUGASTAM_USER;
  process.env.AUGASTAM_USER = 'synthetic-default-user';
  t.after(() => { if (previousUser === undefined) delete process.env.AUGASTAM_USER; else process.env.AUGASTAM_USER = previousUser; });
  const launches = [];
  const launch = (command, args, options) => {
    const child = new EventEmitter();
    child.kill = () => { setImmediate(() => child.emit('exit', null)); return true; };
    launches.push({ options, child });
    if (options.env.PORTAL_AUTH_RUN) setTimeout(() => {
      fs.mkdirSync(options.env.AUTH_DIR, { recursive: true });
      fs.writeFileSync(path.join(options.env.AUTH_DIR, 'admin.json'), '{}');
      fs.writeFileSync(path.join(options.env.AUTH_DIR, 'session.json'), '{}');
      child.emit('exit', 0);
    }, 50);
    return child;
  };
  let portal = createPortal({ dataDir: directory, token: '', launch });
  await new Promise(resolve => portal.server.listen(0, '127.0.0.1', resolve));
  const browser = await chromium.launch({ headless: true });
  t.after(async () => {
    await browser.close(); await portal.close();
    const resolved = fs.realpathSync(directory);
    assert.equal(path.dirname(resolved).toLowerCase(), fs.realpathSync(os.tmpdir()).toLowerCase());
    assert.ok(path.basename(resolved).startsWith('augastam-settings-browser-'));
    fs.rmSync(resolved, { recursive: true, force: true });
  });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  const base = `http://127.0.0.1:${portal.server.address().port}`;
  await page.goto(base);
  await page.getByRole('button', { name: 'Open Augastam' }).click({ timeout: 5000 }).catch(() => {});
  await page.getByRole('link', { name: 'Settings', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Settings', exact: true })).toBeVisible();
  const defaultCard = page.locator('.environment-card').filter({ has: page.getByRole('heading', { name: 'Demo', exact: true }) });
  await expect(defaultCard.getByText('Password configured (hidden)', { exact: true })).toBeVisible();
  await defaultCard.getByRole('button', { name: 'Edit login settings', exact: true }).click();
  await expect(page.getByLabel('Username', { exact: true })).toHaveValue('synthetic-default-user');
  await expect(page.getByLabel('Password', { exact: true })).toHaveValue('');
  await expect(page.getByLabel('Password', { exact: true })).toHaveAttribute('placeholder', 'Saved password configured');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.getByRole('button', { name: 'Add login profile', exact: true }).click();
  await page.getByLabel('Profile ID', { exact: true }).fill('ba-uat');
  await page.getByLabel('Profile name', { exact: true }).fill('BA UAT');
  await page.getByLabel('Website URL', { exact: true }).fill('https://uat.example.test');
  await page.getByLabel('Username', { exact: true }).fill('synthetic-ba');
  await page.getByLabel('Password', { exact: true }).fill('synthetic-test-password');
  await page.getByLabel('Tenant', { exact: true }).fill('Fixture tenant');
  await page.getByLabel('Facility', { exact: true }).fill('Fixture facility');
  await page.getByLabel('Application role', { exact: true }).fill('QA');
  await page.getByRole('button', { name: 'Save login profile', exact: true }).click();
  const card = page.locator('.environment-card').filter({ has: page.getByRole('heading', { name: 'BA UAT', exact: true }) });
  await expect(card).toBeVisible();
  await card.getByRole('button', { name: 'Edit login settings', exact: true }).click();
  await expect(page.getByLabel('Username', { exact: true })).toHaveValue('synthetic-ba');
  await expect(page.getByLabel('Password', { exact: true })).toHaveValue('');
  await page.getByRole('button', { name: 'Save login profile', exact: true }).click();
  await card.getByRole('button', { name: 'Refresh application login', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Refresh BA UAT login', exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Application session refreshed', exact: true })).toBeVisible({ timeout: 15000 });
  await portal.close();
  portal = createPortal({ dataDir: directory, token: '', launch });
  await new Promise(resolve => portal.server.listen(0, '127.0.0.1', resolve));
  await page.goto(`http://127.0.0.1:${portal.server.address().port}/#/settings`);
  await page.getByRole('button', { name: 'Open Augastam' }).click({ timeout: 5000 }).catch(() => {});
  await expect(card.getByText('Session saved', { exact: true })).toBeVisible();
  fs.mkdirSync('portal/test-output', { recursive: true });
  await page.screenshot({ path: 'portal/test-output/settings-profiles.png', fullPage: true });
  await page.getByRole('link', { name: 'Open Module library', exact: true }).click();
  await page.evaluate(() => { location.hash = '#/modules/registration'; });
  await page.getByRole('button', { name: /^Run (approved )?cases$/ }).click();
  await page.getByLabel('Environment', { exact: true }).selectOption('ba-uat');
  await page.getByRole('button', { name: 'Clear', exact: true }).click();
  await page.getByLabel('Include REG-001', { exact: true }).check();
  await page.getByRole('button', { name: 'Create run', exact: true }).click();
  await expect(page.getByText('BA UAT', { exact: false }).first()).toBeVisible();
  await expect.poll(() => launches.length).toBe(2);
  assert.equal(launches[1].options.env.BASE_URL, 'https://uat.example.test');
  assert.equal(launches[1].options.env.AUGASTAM_PASS, '');
  assert.equal(launches[0].options.env.AUGASTAM_USER, 'synthetic-ba');
  assert.deepEqual(errors, []);
});
