import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { chromium, expect } from '@playwright/test';
import { createPortal } from '../server.mjs';

test('BA browser workflow: add modules, write cases, execute manually and edit automated checks', { timeout: 120000 }, async t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'augastam-portal-browser-'));
  const portal = createPortal({ dataDir: directory, token: '', environments: [{ id: 'fixture', name: 'Local UI fixture', url: 'http://application.invalid', authDir: path.join(directory, 'auth') }] });
  await new Promise(resolve => portal.server.listen(0, '127.0.0.1', resolve));
  const browser = await chromium.launch({ headless: true });
  t.after(async () => {
    await browser.close(); await portal.close();
    const resolved = fs.realpathSync(directory);
    assert.equal(path.dirname(resolved).toLowerCase(), fs.realpathSync(os.tmpdir()).toLowerCase());
    assert.ok(path.basename(resolved).startsWith('augastam-portal-browser-'));
    fs.rmSync(resolved, { recursive: true, force: true });
  });
  fs.mkdirSync('portal/test-output', { recursive: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
  page.setDefaultTimeout(10000);
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  await page.goto(`http://127.0.0.1:${portal.server.address().port}`);
  await page.getByRole('button', { name: 'Open Augastam' }).click({ timeout: 5000 }).catch(() => {});
  await expect(page.getByRole('heading', { name: 'Every module. One testing hub.' })).toBeVisible();
  await page.getByRole('button', { name: 'Add module', exact: true }).click();
  await page.getByLabel('Module name', { exact: true }).fill('Facility Setup');
  await page.getByLabel('Business area').fill('Setup');
  await page.getByLabel('Case ID prefix').fill('FAC');
  await page.getByLabel('Description').fill('Facilities, locations and organizational configuration.');
  await page.getByRole('button', { name: 'Create module', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Facility Setup', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Coverage & gaps', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Facility Setup coverage', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Add requirement', exact: true }).first().click();
  await page.getByLabel('Requirement ID', { exact: true }).fill('FAC-REQ-1');
  await page.getByLabel('Requirement description', { exact: true }).fill('Create a facility with a unique name.');
  await page.getByRole('button', { name: 'Add requirement', exact: true }).last().click();
  await expect(page.getByText('No linked cases', { exact: true })).toBeVisible();
  await page.locator('.module-tabs a[href="#/modules/facility-setup"]').click();
  await page.getByRole('button', { name: 'Add test case', exact: true }).first().click();
  await page.getByLabel('Test case title').fill('Create a facility with a unique name');
  await page.getByLabel('Requirement / ticket reference').fill('FAC-REQ-1');
  await page.getByLabel('Step action', { exact: true }).fill('Enter a unique facility name and click Save.');
  await page.getByLabel('Step expected result', { exact: true }).fill('The new facility appears in the list.');
  await page.getByRole('button', { name: 'Save test case', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Create a facility with a unique name', exact: true })).toBeVisible();
  await page.keyboard.press('Control+Shift+B');
  await expect(page.getByRole('heading', { name: 'Create a test run', exact: true })).toBeVisible();
  await page.getByLabel('Run name', { exact: true }).fill('Setup acceptance · browser verification');
  await page.keyboard.press('Control+Shift+B');
  await expect(page.getByRole('heading', { name: 'Setup acceptance · browser verification', exact: true })).toBeVisible();
  await page.locator('summary').click();
  await page.getByLabel('What actually happened?').fill('The saved facility appears in the list.');
  await page.screenshot({ path: 'portal/test-output/manual-evidence.png' });
  await page.locator('input[name="evidence"]').setInputFiles('portal/test-output/manual-evidence.png');
  await page.getByRole('button', { name: 'Save result', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Close run', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Close run', exact: true }).click();
  await expect(page.locator('.run-subline .badge')).toHaveText('passed');
  await page.getByRole('button', { name: 'Report details', exact: true }).click();
  await page.getByLabel('Prepared by', { exact: true }).fill('BA acceptance team');
  await page.getByLabel('Build identifier', { exact: true }).fill('UI-42');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download bug report (PDF)', exact: true }).click();
  const report = await downloadEvent;
  await report.saveAs('portal/test-output/browser-run-report.pdf');
  assert.equal(fs.readFileSync('portal/test-output/browser-run-report.pdf').subarray(0, 5).toString(), '%PDF-');
  await page.goto(`http://127.0.0.1:${portal.server.address().port}/#/modules/facility-setup/coverage`);
  await expect(page.getByText('Linked checks passed', { exact: true })).toBeVisible();
  await page.screenshot({ path: 'portal/test-output/coverage.png', fullPage: true });
  await page.getByRole('link', { name: 'Open evidence →', exact: true }).click();
  await expect(page.locator('.run-subline .badge')).toHaveText('passed');
  await expect(page.locator('.result-case summary')).toContainText('1 screenshot');
  await page.locator('.result-case summary').click();
  await expect(page.getByRole('heading', { name: 'Screenshot evidence (1)', exact: true })).toBeVisible();
  await page.screenshot({ path: 'portal/test-output/manual-run.png', fullPage: true });
  await page.locator('nav a[href="#/modules"]').click();
  await page.getByRole('button', { name: 'Add module', exact: true }).click();
  await page.getByLabel('Module name', { exact: true }).fill('Billing');
  await page.getByLabel('Business area').fill('Finance');
  await page.getByLabel('Case ID prefix').fill('BILL');
  await page.getByLabel('Description').fill('Invoices, payments, discounts and payer workflows.');
  await page.getByRole('button', { name: 'Create module', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Billing', exact: true })).toBeVisible();
  await page.locator('nav a[href="#/modules"]').click();
  await page.screenshot({ path: 'portal/test-output/module-library.png', fullPage: true });
  await page.getByRole('button', { name: 'Setup 1', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Facility Setup', exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Registration', exact: true })).toHaveCount(0);
  await page.getByPlaceholder('Find a module…').fill('missing module');
  await expect(page.locator('.module-card')).toHaveCount(0);
  await page.getByPlaceholder('Find a module…').fill('');
  await page.getByRole('button', { name: 'All modules 3', exact: true }).click();
  await page.locator('.module-card').filter({ has: page.getByRole('heading', { name: 'Registration', exact: true }) }).getByRole('link', { name: 'Open module' }).click();
  await expect(page.getByRole('heading', { name: 'Registration', exact: true })).toBeVisible();
  await page.screenshot({ path: 'portal/test-output/registration-cases.png', fullPage: false });
  await page.getByRole('button', { name: 'Add test case', exact: true }).click();
  const caseId = await page.getByLabel('Case ID', { exact: true }).inputValue();
  assert.match(caseId, /^REG-\d+$/);
  assert.ok(!portal.store.case('registration', caseId));
  await page.getByLabel('Test case title').fill('Reject a short mobile number');
  await page.getByLabel('Starting data template').selectOption('valid');
  await page.getByRole('button', { name: 'Add field', exact: true }).click();
  await page.getByLabel('Input field', { exact: true }).selectOption('mobile');
  await page.getByLabel('Input value', { exact: true }).fill('12345');
  await page.getByRole('button', { name: 'Add field check', exact: true }).click();
  await page.getByLabel('Assertion type').selectOption('fieldErrors');
  await page.getByLabel('Assertion field').selectOption('mobile');
  await page.getByLabel('Expected value', { exact: true }).fill('valid');
  await page.screenshot({ path: 'portal/test-output/case-editor.png', fullPage: false });
  await page.getByRole('button', { name: 'Save test case', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Reject a short mobile number', exact: true })).toBeVisible();
  assert.equal(portal.store.case('registration', caseId).expected.fieldErrors.mobile, 'valid');
  const caseSearch = page.getByPlaceholder('Search ID, title, suite or requirement…');
  await caseSearch.fill('short mobile');
  await expect(page.locator('tbody tr')).toHaveCount(1);
  await expect(page.locator('.list-more')).toHaveText('Showing 1 of 1 matching case');
  // Without a search the table starts at 5 rows; "Load more" adds 5 and focuses the first new case.
  await caseSearch.fill('');
  await expect(page.locator('tbody tr')).toHaveCount(5);
  await expect(page.locator('.list-more')).toContainText(/^Showing 5 of \d+ cases/);
  await page.getByRole('button', { name: 'Load 5 more', exact: true }).click();
  await expect(page.locator('tbody tr')).toHaveCount(10);
  await expect(page.locator('.case-title').nth(5)).toBeFocused();
  // Search also matches the suite name, and a new search starts again from 5 rows.
  await caseSearch.fill('phone');
  await expect(page.locator('tbody tr')).toHaveCount(5);
  await caseSearch.fill('short mobile');
  await expect(page.locator('tbody tr')).toHaveCount(1);
  await page.getByRole('button', { name: `Duplicate ${caseId}`, exact: true }).click();
  await expect(page.getByLabel('Case ID', { exact: true })).not.toHaveValue(caseId);
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await page.getByRole('button', { name: 'Generate with AI', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Create test cases with AI · Registration', exact: true })).toBeVisible();
  await page.getByLabel('How many test cases?').selectOption('3');
  await page.getByRole('button', { name: 'Generate edge cases with AI', exact: true }).click();
  await expect(page.getByRole('heading', { name: '2. Review & accept AI-generated test cases (3 drafts)', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Accept & save selected (3)', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Registration', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Shared data', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Shared test data', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Edit template' }).click();
  await expect(page.getByLabel('Template name')).toHaveValue('valid');
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await page.getByRole('link', { name: 'Design & research' }).click();
  await expect(page.getByRole('heading', { name: 'Familiar patterns. Your workflow.' })).toBeVisible();
  assert.equal(await page.locator('.research-card').count(), 6);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(`http://127.0.0.1:${portal.server.address().port}/#/modules`);
  await expect(page.getByRole('heading', { name: 'Every module. One testing hub.' })).toBeVisible();
  await page.screenshot({ path: 'portal/test-output/mobile.png', fullPage: true });
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 2);
  assert.equal(overflow, false, 'The mobile workspace must not overflow horizontally.');
  assert.deepEqual(errors, [], 'No browser errors or CSP violations.');
});
